import { NOT_GIVEN } from '../reading/read.ts'
import { CHOICES, DEFAULT_CHOICE } from '../view/periods.ts'
import { FAMILY_TAB, SUMMARY_TAB } from './tabs.ts'

/**
 * Текст справки: по разделу на экран, о данных и «если что-то не так».
 *
 * Справка только описывает: названия кнопок, вкладок и полей — те же, что
 * на экранах; вкладки и отрезки — из их констант. Цифрами здесь ничего
 * не пишется (тест `help.test.ts`): число, которое может поменяться, берётся
 * из константы кода.
 */

export type HelpSection = {
  /** Постоянный ключ блока: по нему устройство помнит, что свёрнуто. */
  id: string
  title: string
  paragraphs: readonly string[]
}

const quoted = (names: readonly string[]) => names.map((name) => `«${name}»`).join(', ')

export function helpSections(title: string): readonly HelpSection[] {
  const summary = `«${SUMMARY_TAB.name}»`
  const family = `«${FAMILY_TAB.name}»`
  const choice = CHOICES.find((item) => item.id === DEFAULT_CHOICE)?.label ?? ''

  return [
    {
      id: 'help:summary',
      title: SUMMARY_TAB.name,
      paragraphs: [
        `Главный экран: что было у приложений семьи за неделю или месяц и кто из них зовёт. Каждое число — как его посчитало само приложение, со своим основанием мелко под строкой. «${title}» ничего не досчитывает: ни сумм, ни средних, ни сравнений между приложениями.`,
        `«Зовут» — что приложения просят сделать: подпись, за какой день и «открыть» — ссылка в само приложение. Если никто не зовёт, так и сказано.`,
        `Переключатель отрезка: ${quoted(CHOICES.map((item) => item.label))}. По умолчанию — «${choice}». У идущего отрезка написано «идёт, по» и день.`,
        `Ниже — связки, если они заведены в ${family}, и блок каждого приложения в порядке из ${family}. Вверху блока — «посчитано»: когда приложение посчитало срез, и «по записям по»: день последней записи в нём. Под строками одного ряда — например, времени по группам — полоса: самая большая во всю ширину, остальные в том же масштабе. Списки названий, если приложение их отдаёт, стоят в его блоке на любом отрезке.`,
        `Срезы читаются при открытии экрана и кнопкой «Обновить»; сами, в фоне, — нет. Блоки сворачиваются тапом по заголовку, у свёрнутого рядом виден итог; что свёрнуто, устройство помнит.`,
      ],
    },
    {
      id: 'help:family',
      title: FAMILY_TAB.name,
      paragraphs: [
        `Список приложений, чьи итоги видны в ${summary}. Список ведёшь ты: «${title}» сам приложений не находит.`,
        `«Добавить приложение» открывает форму: имя — как подписывать на экранах; репозиторий данных — «владелец/имя» или ссылка на него, оттуда читается срез; сайт приложения — адрес любого его экрана; порядок — меньше стоит выше.`,
        `У каждого приложения — что с его срезом, теми же словами, что в ${summary}, его репозиторий и сайт. «Поправить» открывает форму прямо в блоке, «Убрать» убирает приложение из списка — увиденные срезы останутся в архиве.`,
        `Строка «имя на устройстве» сверяет имя репозитория, которое знает само приложение на этом устройстве, со списком. Пустое вписывается при чтении само. Другое не меняется без тебя: кнопка «Записать имя из списка» переписывает его именем из списка.`,
        `«Как установить» — ссылка на сайт каждого приложения: поставить его отсюда браузер не даёт, только с его собственного сайта.`,
      ],
    },
    {
      id: 'help:bundles',
      title: 'Связки',
      paragraphs: [
        `Связка ставит рядом в ${summary} строки разных приложений про одно и то же — например, время из одного и записи из другого. Ничего не складывает и не сравнивает: каждая строка — как её посчитало своё приложение, со своим основанием и датой.`,
        `Заводятся в ${family}, в блоке «Связки» ниже приложений: «Новая связка», имя, порядок и строки флажками по приложениям. Строка бывает только в одной связке — в другой она недоступна. «Поправить» и «Убрать» — в блоке связки.`,
        `В ${summary} связки стоят между переключателем отрезка и приложениями. Строки нет в этом отрезке — «нет в срезе за этот отрезок». Строка пропала из среза совсем — например, группу переименовали — рядом ссылка «поправь связку»: она открывает связку в ${family}, там пропавшая помечена «нет в последнем срезе».`,
      ],
    },
    {
      id: 'help:settings',
      title: 'Настройки',
      paragraphs: [
        `Открываются шестерёнкой в шапке. Разделы свёрнуты, пока их не открыли.`,
        `«Синхронизация» — токен «семья» и свой репозиторий данных. Под ней — «Как переезжает список» и «Как настроить новое устройство»: по шагам, что вписать и в каком порядке.`,
        `«Доступ к приложениям» — кнопка «Проверить доступ к приложениям»: видит ли токен репозиторий данных каждого приложения из ${family}.`,
        `«Название» — как называть приложение на этом устройстве; «Как было» возвращает прежнее.`,
        `«Копия данных» — «Сохранить в файл» и «Восстановить из копии». Восстановление ничего не стирает: записи сливаются, побеждает более поздняя правка.`,
        `«Копия всей семьи» — кнопка «Скачать копию»: одним файлом всё, что приложения из ${family} уже синхронизировали в свои репозитории данных, и репозиторий данных самого «${title}» — список приложений, связки, увиденные срезы; нужен токен «семья». Запасной путь на случай потери аккаунта GitHub. Под кнопкой — у каждого приложения, сколько файлов в копии или почему не прочитано: нечитаемое копию не останавливает. Свой репозиторий не вписан в «Синхронизацию» — в файле он с этой причиной. Вернуть данные из такой копии — руками, по шагам из ссылки в том же разделе: новые репозитории данных, те же файлы теми же путями, синхронизация.`,
        `«Телеграм-бот» — «Скачать список для бота»: бот живёт в твоём приватном репозитории и присылает в личный чат то же, что ${summary}. Поменял приложения в ${family} — скачай список заново.`,
        `«О приложении» — сборка, что лежит в базе, «Что нового» и «Сообщить об ошибке».`,
      ],
    },
    {
      id: 'help:data',
      title: 'Данные и синхронизация',
      paragraphs: [
        `«${title}» своих записей о жизни не ведёт. Каждое приложение семьи, когда его открывают с сетью, само кладёт в свой репозиторий данных срез итогов — короткий файл: неделя, месяц, кто зовёт, каждая строка с основанием. Здесь читается только он; сами записи приложений — нет. Исключение одно — «Копия всей семьи» в настройках: по кнопке она читает все файлы репозиториев данных, только читает, ничего в них не пишет, и токена в файле нет.`,
        `Поэтому срез свеж настолько, насколько недавно открывали его приложение. Срез посчитан давно и нужной недели или месяца в нём нет — «не известно» и день, когда он посчитан. Строки нет в срезе — значит, приложение её за этот отрезок не отдало; почему — решает само приложение, здесь не угадывается.`,
        `На этом устройстве хранятся список приложений, связки и увиденные срезы. Нет связи — показан последний прочитанный срез с датой.`,
        `Синхронизация увозит их в твой репозиторий данных и привозит на другие устройства; как именно — «Настройки» → «Синхронизация» → «Как переезжает список». Токен «семья» — один на все приложения семьи на устройстве; ни в синхронизацию, ни в копию данных он не входит.`,
      ],
    },
    {
      id: 'help:trouble',
      title: 'Если что-то не так',
      paragraphs: [
        `«Не настроено: нет токена» — впиши токен «семья» в «Настройки» → «Синхронизация» или в любом приложении семьи на этом устройстве.`,
        `«Токен не видит репозиторий» — опечатка в имени репозитория в ${family} или токен выдан не на него. Сверь в «Настройки» → «Доступ к приложениям».`,
        `«Токен не принят» — у токена истёк срок, его отозвали или вписали не целиком: выпусти новый и впиши заново.`,
        `«${NOT_GIVEN}» — в репозитории приложения ещё нет среза. Открой само приложение с сетью; если не помогло — эта его версия срез пока не отдаёт.`,
        `Старая дата у «посчитано» или «не известно» — открой то приложение с сетью, потом здесь «Обновить».`,
        `«Сейчас нет связи» — показан последний прочитанный срез; со связью нажми «Обновить».`,
        `Срез «не сходится с формой» — приложение и «${title}» разных версий: обнови оба, закрыв и открыв заново.`,
        `«Имя на устройстве другое» или приложения задвоились после синхронизации — «Настройки» → «Синхронизация» → «Как настроить новое устройство» и «Как переезжает список».`,
        `Не помогло — «Настройки» → «О приложении» → «Сообщить об ошибке».`,
      ],
    },
  ]
}
